def _build_academic_latex(title: str, chapters: list[dict[str, Any]], author: str) -> str:
    """Build LaTeX content for academic paper style storybook."""

    latex = f"""% D&D Academic Paper Style Storybook
% Generated by WAFT Storyteller
% Title: {escape_latex(title)}

\\documentclass[11pt,letterpaper,twocolumn]{{article}}

\\usepackage[utf8]{{inputenc}}
\\usepackage[T1]{{fontenc}}
\\usepackage{{geometry}}
\\usepackage{{fancyhdr}}
\\usepackage{{titlesec}}
\\usepackage{{xcolor}}
\\usepackage{{abstract}}
\\usepackage{{booktabs}}

% Academic paper geometry
\\geometry{{
    left=0.75in,
    right=0.75in,
    top=0.75in,
    bottom=0.75in
}}

% Academic colors
\\definecolor{{acblack}}{{RGB}}{{0,0,0}}
\\definecolor{{acblue}}{{RGB}}{{0,51,102}}

% Page style
\\pagestyle{{fancy}}
\\fancyhf{{}}
\\fancyhead[C]{{\\textsc{{{escape_latex(title)}}}}}
\\fancyfoot[C]{{\\thepage}}
\\renewcommand{{\\headrulewidth}}{{0.4pt}}

% Title formatting
\\titleformat{{\\section}}
    {{\\large\\bfseries\\color{{acblack}}}}
    {{}}
    {{0em}}
    {{}}
    [\\titlerule[0.4pt]]

% Document metadata
\\title{{{escape_latex(title)}}}
\\author{{{escape_latex(author)}}}
\\date{{\\today}}

\\begin{{document}}

\\twocolumn[
\\maketitle
\\begin{{abstract}}
This document presents a comprehensive narrative in academic paper format, 
combining scholarly presentation with adventure storytelling.
\\end{{abstract}}
]

"""

    # Add chapters as sections
    for i, chapter in enumerate(chapters, 1):
        chapter_title = chapter.get("title", f"Section {i}")
        chapter_content = chapter.get("content", "")

        latex += f"""
\\section{{{escape_latex(chapter_title)}}}

"""

        # Add content (simplified)
        from src.waft.templates.dnd5e_latex import _format_chapter_content

        latex += _format_chapter_content(chapter_content)

        latex += "\n"

    latex += """\\end{document}
"""

    return latex


def list_templates():
    """List available book template styles."""
    templates = [
        ("dnd", "D&D 5e Official Style (default)"),
        ("field-guide", "Field Guide Style (practical, rugged)"),
        ("academic", "Academic Paper Style (two-column, scholarly)"),
    ]

    table = Table(title="Available Book Templates")
    table.add_column("Template", style="cyan")
    table.add_column("Description", style="green")

    for name, desc in templates:
        table.add_row(name, desc)

    console.print(table)


def main():
    parser = argparse.ArgumentParser(
        description="Evolve book template - create new template variants"
    )
    parser.add_argument(
        "--template", choices=["dnd", "field-guide", "academic"], help="Template style to use"
    )
    parser.add_argument("--list", action="store_true", help="List available templates")
    parser.add_argument("--title", help="Book title")
    parser.add_argument("--file", type=Path, help="Input file with chapters")
    parser.add_argument("--demo", action="store_true", help="Use demo content")

    args = parser.parse_args()

    if args.list:
        list_templates()
        return

    if not args.template:
        console.print("[red]Error: --template required (use --list to see options)[/red]")
        return

    # Get book content
    if args.demo:
        from scripts.create_book import create_sample_chapters

        chapters = create_sample_chapters()
        title = "Demo Adventure Book"
    elif args.file:
        from scripts.create_book import parse_chapters_from_file

        chapters = parse_chapters_from_file(args.file)
        title = args.title or args.file.stem
    elif args.title:
        console.print("[red]Error: Need --file or --demo for content[/red]")
        return
    else:
        console.print("[red]Error: Need --title with --file or --demo[/red]")
        return

    if not title:
        title = "Untitled Book"

    console.print(f"[green]Generating book with {args.template} template...[/green]")

    # Generate based on template
    try:
        if args.template == "field-guide":
            output_path = generate_field_guide_storybook_latex(
                title=title, chapters=chapters, author="WAFT Storyteller"
            )
        elif args.template == "academic":
            output_path = generate_academic_storybook_latex(
                title=title, chapters=chapters, author="WAFT Storyteller"
            )
        else:  # dnd
            output_path = generate_storybook_latex(
                title=title, chapters=chapters, author="WAFT Storyteller"
            )

        console.print(f"[green]✅ Book generated: {output_path}[/green]")

        # Try to open
        import platform
        import subprocess

        if platform.system() == "Darwin":
            subprocess.run(["open", str(output_path)])

    except Exception as e:
        console.print(f"[red]❌ Error: {e}[/red]")
        import traceback

        traceback.print_exc()


if __name__ == "__main__":
    main()
