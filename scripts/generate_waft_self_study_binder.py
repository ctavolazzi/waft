def combine_all_pdfs(pdf_files: List[Path], output_path: Path) -> Path:
    """Combine all PDFs into master binder using pypdf/PyPDF2."""
    print("\n📚 Combining all PDFs into master binder...")
    
    # Try pypdf first (newer package uses PdfWriter), then PyPDF2 (uses PdfMerger)
    try:
        from pypdf import PdfWriter, PdfReader
        
        writer = PdfWriter()
        
        for pdf_file in sorted(pdf_files):
            if pdf_file.exists():
                print(f"   - Adding: {pdf_file.name}")
                try:
                    reader = PdfReader(str(pdf_file))
                    for page in reader.pages:
                        writer.add_page(page)
                except Exception as e:
                    print(f"      ⚠️  Error adding {pdf_file.name}: {e}")
        
        with open(output_path, 'wb') as f:
            writer.write(f)
        
        # Count pages
        try:
            reader = PdfReader(str(output_path))
            page_count = len(reader.pages)
        except:
            page_count = "unknown"
        
        print(f"\n✅ Master binder created: {output_path}")
        print(f"   - Pages: {page_count}")
        print(f"   - PDFs: {len([p for p in pdf_files if p.exists()])}")
        
        return output_path
    except ImportError:
        try:
            from PyPDF2 import PdfMerger, PdfReader
            
            merger = PdfMerger()
            
            for pdf_file in sorted(pdf_files):
                if pdf_file.exists():
                    print(f"   - Adding: {pdf_file.name}")
                    try:
                        merger.append(str(pdf_file))
                    except Exception as e:
                        print(f"      ⚠️  Error adding {pdf_file.name}: {e}")
            
            merger.write(str(output_path))
            merger.close()
            
            # Count pages
            try:
                reader = PdfReader(str(output_path))
                page_count = len(reader.pages)
            except:
                page_count = "unknown"
            
            print(f"\n✅ Master binder created: {output_path}")
            print(f"   - Pages: {page_count}")
            print(f"   - PDFs: {len([p for p in pdf_files if p.exists()])}")
            
            return output_path
        except ImportError:
            print("   ❌ Neither pypdf nor PyPDF2 available. Install with: pip install pypdf")
            raise
    except ImportError:
        print("   ❌ PyPDF2 not available. Install with: pip install PyPDF2")
        raise


