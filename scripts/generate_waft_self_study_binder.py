    print("\n📄 Generating Cover & Table of Contents...")
    
    config = DocumentConfig.clinical_standard(
        header="WAFT SELF-STUDY RESEARCH BINDER",
        watermark=None,
    )
    config.title = "WAFT Self-Study PDF Research Binder"
    config.author = "WAFT Self-Study System"
    
    engine = DocumentEngine(config)
    
    # Cover page
    engine.add(CoverPage(
        institution="WAFT SELF-STUDY RESEARCH BINDER",
        division="Comprehensive PDF Generation Capability Documentation",
        document_type="RESEARCH BINDER",
        document_number="Binder No. 001-SELF-STUDY",
        classification="INTERNAL DOCUMENTATION",
    ))
    
    # Table of Contents
    engine.add(SectionHeader("Table of Contents", level=1))
    engine.add(TextBlock(
        "This binder contains comprehensive documentation of WAFT's PDF generation "
        "capabilities, generated by WAFT itself as a self-study exercise."
    ))
    engine.add(RuleBlock())
    
    toc_items = [
        ("00", "Cover & Table of Contents", "This document"),
        ("01", "System Architecture & Philosophy", "WAFT's PDF generation philosophy and architecture"),
        ("02", "Generator Showcase", "Demonstration of all PDF generators"),
        ("03", "Styling Genome System", "Font, margin, color, and layout configuration"),
        ("04", "Foundation V2 Block Library", "All available content blocks"),
        ("05", "Template Library Catalog", "Available template system templates"),
        ("06", "Research Tools - Forms & Reports", "Bureaucratic forms for self-study"),
        ("07", "Evidence Catalogue", "Code inventory, API reference, and metrics"),
        ("08", "Technical Specifications", "Dependencies, file structure, and schemas"),
        ("09", "Self-Study Findings Report", "Methodology, findings, and recommendations"),
    ]
    
    engine.add(TableBlock(
        headers=["Section", "Title", "Description"],
        rows=[[item[0], item[1], item[2]] for item in toc_items]
    ))
    
    output_path = output_dir / "00_cover_and_toc.pdf"
    engine.render(output_path)
    print(f"   ✅ Created: {output_path.name}")
    return output_path


