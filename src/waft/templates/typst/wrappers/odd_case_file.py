def compile_odd_document(
    typst_source: str,
    output_path: Path,
    root_dir: Path | None = None,
) -> Path:
    """Compile Typst source to PDF."""
    # Create temp file for source
    temp_typ = output_path.with_suffix(".typ")
    temp_typ.write_text(typst_source)

    try:
        cmd = ["typst", "compile"]
        if root_dir:
            cmd.extend(["--root", str(root_dir)])
        cmd.extend([str(temp_typ), str(output_path)])

        result = subprocess.run(cmd, capture_output=True, text=True, check=True)
        return output_path
    finally:
        # Optionally keep the .typ file for debugging
        pass


def generate_odd_case_file(
    config: ODDCaseFile,
    output_dir: Path | None = None,
) -> Path:
    """Generate an ODD case file PDF."""
    if output_dir is None:
        output_dir = Path("_realms/odd_realm/output")
    output_dir.mkdir(parents=True, exist_ok=True)

    output_path = output_dir / f"{config.case_id}.pdf"
    typst_source = generate_case_file_typst(config)

    return compile_odd_document(typst_source, output_path)


def generate_odd_interview(
    config: ODDInterview,
    output_dir: Path | None = None,
) -> Path:
    """Generate an ODD interview PDF."""
    if output_dir is None:
        output_dir = Path("_realms/odd_realm/output")
    output_dir.mkdir(parents=True, exist_ok=True)

    output_path = output_dir / f"{config.interview_id}.pdf"
    typst_source = generate_interview_typst(config)

    return compile_odd_document(typst_source, output_path)


