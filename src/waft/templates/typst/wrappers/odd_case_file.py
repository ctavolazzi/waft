# Classification levels
Classification = Literal["WITNESSED", "ARCHIVED", "CONVERGENCE EYES ONLY"]


@dataclass
class ODDCaseFile:
    """Configuration for an ODD case file."""

    case_id: str
    subject: str
    observer: str = "WITNESS-001"
    classification: Classification = "WITNESSED"
    summary: str = ""
    observations: list[str] = field(default_factory=list)
    analysis: str = ""
    implications: str = ""
    stability_index: float = 0.94
    archive_ref: str = ""

    def __post_init__(self):
        """Validate case file data."""
        if not self.case_id:
            raise ValueError("Case ID is required")
        if not self.subject:
            raise ValueError("Subject is required")
        if not self.archive_ref:
            self.archive_ref = f"NX-{self.case_id.replace('ODD-CF-', '')}"


@dataclass
class ODDInterview:
    """Configuration for an ODD interview transcript."""

    interview_id: str
    participants: list[str]
    classification: Classification = "WITNESSED"
    exchanges: list[tuple[str, str]] = field(default_factory=list)
    stability_index: float = 0.94
    archive_ref: str = ""

    def __post_init__(self):
        """Validate interview data."""
        if not self.interview_id:
            raise ValueError("Interview ID is required")
        if not self.participants or len(self.participants) < 2:
            raise ValueError("At least two participants required")
        if not self.archive_ref:
            self.archive_ref = f"NX-{self.interview_id.replace('ODD-INT-', '')}"


def _escape_typst(text: str) -> str:
    """Escape special characters for Typst."""
    # Escape backslashes first, then other special chars
    text = text.replace("\\", "\\\\")
    text = text.replace("#", "\\#")
    text = text.replace("$", "\\$")
    text = text.replace("@", "\\@")
    return text


