@dataclass
class Observation:
    """An observation about the codebase."""

    timestamp: str
    component: str  # Which part of WAFT
    observation: str  # What was observed
    documentation_status: str  # "documented", "undocumented", "outdated"
    priority: str = "medium"  # "low", "medium", "high", "critical"
    suggested_action: Optional[str] = None


@dataclass
class DocumentationGap:
    """A gap in documentation that should be filled."""

    component: str
    gap_type: str  # "missing", "incomplete", "outdated", "unclear"
    description: str
    current_state: str  # What exists now
    desired_state: str  # What should exist
    priority: str = "medium"


@dataclass
class ReflectionReport:
    """A report generated by the reflection system."""

    timestamp: str
    observations: List[Observation] = field(default_factory=list)
    gaps: List[DocumentationGap] = field(default_factory=list)
    recommendations: List[str] = field(default_factory=list)
    metrics: Dict[str, any] = field(default_factory=dict)


class ReflectionSystem:
    """
    WAFT's self-reflection and documentation system.

    This system observes WAFT's codebase, identifies documentation gaps,
    and helps maintain clear, current, consistent documentation.

    The Four Cs of Documentation:
    - CLEAR: Easy to understand
    - CLEAN: Well-organized
    - CURRENT: Up-to-date
    - CONSISTENT: Unified style/format

    Example:
        reflector = ReflectionSystem(waft_root=Path("src/waft"))

        # Observe current state
        report = reflector.reflect()

        # Generate documentation for gaps
        reflector.document_gaps(report)

        # Create self-documentation
        reflector.generate_architecture_doc()
    """

    def __init__(self, waft_root: Path):
        self.waft_root = waft_root
