def run_reflection_example():
    """Example: Run reflection and generate report."""
    reflector = ReflectionSystem(waft_root=Path("src/waft"))

    print("Running WAFT reflection...")
    report = reflector.reflect()

    print()
    print("=" * 70)
    print("REFLECTION REPORT SUMMARY")
    print("=" * 70)
    print()

    for key, value in report.metrics.items():
        print(f"{key}: {value}")

    print()
    print("Recommendations:")
    for rec in report.recommendations:
        print(f"  {rec}")

    print()
    print("Generating reflection report PDF...")

    report_path = Path("_work_efforts/WAFT_Reflection_Report.pdf")
    reflector.generate_reflection_report_doc(report, report_path)

    print(f"✓ Report saved: {report_path}")

    return report


